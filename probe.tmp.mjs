import { chromium } from '@playwright/test';
const SC = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1280, height: 800 }, colorScheme: 'dark' });
await p.goto('http://127.0.0.1:4599/dev/renderer', { waitUntil: 'load', timeout: 45000 });
await p.waitForTimeout(1500);
await p.selectOption('select', 'quieto');
await p.waitForTimeout(2500);
await p.screenshot({ path: SC + '/fix-donut.png' });
await p.selectOption('select', 'tarta');
await p.waitForTimeout(2500);
await p.screenshot({ path: SC + '/fix-tarta.png' });
await b.close();
console.log('ok');
